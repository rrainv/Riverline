// node eqtest.js [theme] [html-or-url]
const { chromium } = require('playwright');
const path = require('path');
const { pathToFileURL } = require('url');

const th = process.argv[2] || 'midnight';
const target = process.argv[3] || path.join(__dirname, '..', 'prototypes', 'riverline-app.html');
const toUrl = (t) => (/^https?:\/\/|^file:\/\//i.test(t) ? t : pathToFileURL(path.resolve(t)).href);

(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
  const errs = [];
  p.on('pageerror', (e) => errs.push(String(e)));
  await p.goto(toUrl(target));
  await p.waitForTimeout(500);
  const read = () => p.evaluate(() => Array.from(document.querySelectorAll('.eqrow')).map((r) => r.innerText.replace(/\s+/g, ' ')));
  await p.evaluate((th) => window.__comp.setState({ view: 'equity', turn: null, th }), th);
  await p.waitForTimeout(600);
  console.log('flop 2p', await read());
  await p.screenshot({ path: 'eq_flop_' + th + '.png' });
  await p.evaluate(() => window.__comp.setState({ turn: 'Js' }));
  await p.waitForTimeout(300);
  console.log('Js', await read());
  await p.focus('input[aria-label^="Add a player"]');
  await p.keyboard.type('th 9h');
  await p.keyboard.press('Enter');
  await p.waitForTimeout(400);
  await p.evaluate(() => window.__comp.setState({ turn: null }));
  await p.waitForTimeout(300);
  console.log('flop 3p', await read());
  await p.evaluate(() => window.__comp.setState({ turn: '3h' }));
  await p.waitForTimeout(300);
  console.log('3h 3p', await read());
  await p.focus('input[aria-label^="Add a player"]');
  await p.keyboard.type('Qh2c');
  await p.keyboard.press('Enter');
  await p.waitForTimeout(300);
  console.log('err', await p.evaluate(() => (document.querySelector('[role=alert]') || {}).innerText));
  await p.fill('input[aria-label^="Add a player"]', '');
  await p.click('text=smaller set');
  await p.waitForTimeout(400);
  await p.evaluate(() => window.__comp.setState({ turn: null }));
  await p.waitForTimeout(300);
  console.log('flop 4p', await read());
  await p.focus('.tgrid');
  await p.keyboard.press('ArrowRight');
  await p.waitForTimeout(200);
  await p.keyboard.press('ArrowRight');
  await p.waitForTimeout(200);
  await p.keyboard.press('ArrowDown');
  await p.waitForTimeout(300);
  console.log('kbd', await p.evaluate(() => document.querySelector('.h2[style*="margin:0"]').innerText));
  await p.screenshot({ path: 'eq_4p_' + th + '.png' });
  await p.keyboard.press('Escape');
  await p.waitForTimeout(200);
  console.log('esc', await p.evaluate(() => document.querySelector('.h2[style*="margin:0"]').innerText));
  await p.click('.eqx');
  await p.waitForTimeout(300);
  console.log('after remove', (await read()).length, 'errs', errs);
  await b.close();
  if (errs.length > 0) process.exit(1);
})();
